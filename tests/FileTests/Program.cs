using System.Text;
using MarkdownEditor;

var directory = Path.GetFullPath(Path.Combine("artifacts", "file-tests", Guid.NewGuid().ToString("N")));
Directory.CreateDirectory(directory);
int passed = 0;
void Check(bool condition) { if (!condition) throw new Exception("Assertion failed"); passed++; }
void Throws(Action action) { try { action(); } catch (Exception e) when (e is IOException or DecoderFallbackException) { passed++; return; } throw new Exception("Expected file operation failure"); }
var text = "# Привіт\r\n\r\n**Український текст**\r\n";
Check(DocumentFiles.Decode(Encoding.UTF8.GetBytes(text)) == text);
Check(DocumentFiles.Decode(Encoding.UTF8.GetPreamble().Concat(Encoding.UTF8.GetBytes(text)).ToArray()) == text);
Check(DocumentFiles.Decode(Encoding.Unicode.GetPreamble().Concat(Encoding.Unicode.GetBytes(text)).ToArray()) == text);
Check(DocumentFiles.Decode(Encoding.BigEndianUnicode.GetPreamble().Concat(Encoding.BigEndianUnicode.GetBytes(text)).ToArray()) == text);
Throws(() => DocumentFiles.Decode(new byte[] { 0xff, 0xff, 0x80 }));
Throws(() => DocumentFiles.Decode(new byte[] { 0xff, 0xfe, 0, 0, 1, 0, 0, 0 }));
var path = Path.Combine(directory, "test.md");
var original = DocumentFiles.Save(path, text, null, false);
Check(DocumentFiles.Decode(DocumentFiles.ReadBytes(path)) == text);
var updated = DocumentFiles.Save(path, text + "Зміни", original, true);
Check(DocumentFiles.ReadBytes(path).SequenceEqual(updated));
File.WriteAllText(path, "Зовнішні зміни");
Throws(() => DocumentFiles.Save(path, "Overwrite", updated, true));
Check(File.ReadAllText(path) == "Зовнішні зміни");
File.Delete(path);
Throws(() => DocumentFiles.Save(path, text, updated, true));
Throws(() => DocumentFiles.ReadBytes(Path.Combine(directory, "missing.md")));
Throws(() => DocumentFiles.Save(Path.Combine(directory, "missing", "file.md"), text, null, false));
Throws(() => DocumentFiles.Save(path, new string('x', DocumentFiles.MaxBytes + 1), null, false));
Check(Directory.GetFiles(directory, "*.tmp").Length == 0);
var recoveryRoot = Path.Combine(directory, "Recovery");
var store = new RecoveryStore(recoveryRoot);
var draft = new RecoveryDraft(1, path, "Unsaved Привіт", "Saved", Encoding.UTF8.GetBytes("Saved"), DateTime.UtcNow, 0, 0);
store.Write(draft);
var otherSession = new RecoveryStore(recoveryRoot);
var available = otherSession.Available(); Check(available.Count == 1); Check(available[0].Draft.Markdown == draft.Markdown); Check(available[0].Draft.DiskBytes!.SequenceEqual(draft.DiskBytes!));
store.Write(draft with { Markdown = "Latest" }); Check(otherSession.Available().Single().Draft.Markdown == "Latest");
using (var process = System.Diagnostics.Process.GetCurrentProcess()) store.Write(draft with { ProcessId = process.Id, ProcessStartedTicks = process.StartTime.ToUniversalTime().Ticks });
Check(otherSession.Available().Count == 0);
store.KeepCopy(draft); Check(otherSession.Available().Single().Draft.Markdown == draft.Markdown);
File.WriteAllText(Path.Combine(recoveryRoot, Guid.NewGuid().ToString("N") + ".json"), "broken json");
Check(otherSession.Available().Count == 1);
otherSession.Remove(otherSession.Available().Single()); Check(otherSession.Available().Count == 0);
store.Clear(); Check(Directory.GetFiles(recoveryRoot, "*.tmp").Length == 0);
Throws(() => store.Write(draft with { Markdown = new string('x', DocumentFiles.MaxBytes + 1) }));
Throws(() => otherSession.Remove(new RecoveryEntry(Path.Combine(directory, "outside.json"), draft)));
var images = Path.Combine(directory, "images"); Directory.CreateDirectory(images);
var imageFile = Path.Combine(images, "тест.png"); File.WriteAllBytes(imageFile, [137, 80, 78, 71]);
var relative = DocumentImages.Relative(path, imageFile); Check(DocumentImages.Read(path, relative)!.Value.Bytes.Length == 4);
Check(DocumentImages.Resolve(path, "../outside.png") is null); Check(DocumentImages.Resolve(path, "https://example.com/image.png") is null); Check(DocumentImages.Resolve(path, "file:///secret.png") is null); Check(DocumentImages.Resolve(path, "images/a.txt") is null);
var renamed = DocumentImages.RenameCopy(path, relative, "new.png"); Check(File.Exists(imageFile)); Check(File.Exists(DocumentImages.Resolve(path, renamed)));
Throws(() => DocumentImages.RenameCopy(path, relative, "../escape.png")); Throws(() => DocumentImages.RenameCopy(path, relative, "new.svg"));
var targetFolder = Path.Combine(directory, "saved-as"); Directory.CreateDirectory(targetFolder); var targetDocument = Path.Combine(targetFolder, "new.md");
DocumentImages.CopyForSaveAs(path, targetDocument, [relative]); Check(DocumentImages.Read(targetDocument, relative)!.Value.Bytes.SequenceEqual(new byte[] { 137, 80, 78, 71 }));
File.WriteAllBytes(DocumentImages.Resolve(targetDocument, relative)!, [1]); Throws(() => DocumentImages.CopyForSaveAs(path, targetDocument, [relative]));
Check(DocumentImages.EmbedHtml($"<img src=\"{relative}\">", path).Contains("data:image/png;base64,"));
Console.WriteLine($"Passed {passed} file/encoding/conflict assertions.");
